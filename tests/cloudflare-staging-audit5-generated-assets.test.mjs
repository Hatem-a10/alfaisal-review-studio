import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync,writeFileSync,existsSync,statSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {writeVerifiedBinary,writeGeneratedText,encodeGeneratedAssetOutputs} from '../scripts/generated-asset-output.mjs';

test('A5-263: generated registry and diagram outputs match legacy bytes exactly',()=>{
 const a=[{id:'heart-v1',sha:'abc',size:12,type:'model/gltf-binary'}],b={'/api/site-assets/a.png':{width:1400,height:900,480:'/api/study-assets/p'}};
 const actual=encodeGeneratedAssetOutputs(a,b);
 const expected=[
 ['lib/study-asset-registry.ts','// Generated by prepare-study-assets.mjs; media live in private R2.\nexport const STUDY_ASSETS='+JSON.stringify(a)+';\n'],
 ['public/diagram-variants.json',JSON.stringify(b)],
 ['public/diagram-variants.js','const DIAGRAM_VARIANTS='+JSON.stringify(b)+';\n'],
 ['../heart-lab-work/asset-files.json',JSON.stringify(a)]
 ];
 assert.deepEqual(actual,expected);assert.equal(new Set(actual.map(x=>x[0])).size,4);
});
test('A5-263: deterministic text outputs skip identical writes but repair changed outputs',()=>{
 const dir=mkdtempSync(join(tmpdir(),'review-a5-263-'));
 try{const file=join(dir,'registry.json');assert.equal(writeGeneratedText(file,'{"x":1}'),true);const before=statSync(file).mtimeMs;assert.equal(writeGeneratedText(file,'{"x":1}'),false);assert.equal(statSync(file).mtimeMs,before);writeFileSync(file,'bad');assert.equal(writeGeneratedText(file,'{"x":1}'),true);assert.equal(readFileSync(file,'utf8'),'{"x":1}');}finally{rmSync(dir,{recursive:true,force:true})}
});
test('A5-277: immutable staged bytes skip redundant writes but repair same-length corruption',()=>{
 const dir=mkdtempSync(join(tmpdir(),'review-a5-277-'));
 try{const file=join(dir,'asset'),good=Buffer.from('12345678');assert.equal(existsSync(file),false);
 assert.equal(writeVerifiedBinary(file,good),true);const before=statSync(file).mtimeMs;
 assert.equal(writeVerifiedBinary(file,Buffer.from('12345678')),false);assert.equal(statSync(file).mtimeMs,before);
 writeFileSync(file,'87654321');assert.equal(writeVerifiedBinary(file,good),true);assert.deepEqual(readFileSync(file),good);
 assert.equal(writeVerifiedBinary(file,Buffer.from('different length')),true);assert.equal(readFileSync(file,'utf8'),'different length');
 }finally{rmSync(dir,{recursive:true,force:true})}
});
test('A5-263 and A5-277 require no extra bytes or writes when outputs are unchanged',()=>{
 let writes=0,reads=0;const values=new Map(),io={
 existsSync:p=>values.has(p),
 statSync:p=>({size:values.get(p).length}),
 readFileSync:(p,encoding)=>{reads++;const b=values.get(p);return encoding==='utf8'?b.toString('utf8'):Buffer.from(b)},
 writeFileSync:(p,b)=>{writes++;values.set(p,Buffer.isBuffer(b)?Buffer.from(b):Buffer.from(b))}
 };
 for(const [path,content] of encodeGeneratedAssetOutputs([{id:'a'}],{a:{width:900}}))assert.equal(writeGeneratedText(path,content,io),true);
 assert.equal(writeVerifiedBinary('asset',Buffer.alloc(1024,3),io),true);
 assert.equal(writes,5);
 for(const [path,content] of encodeGeneratedAssetOutputs([{id:'a'}],{a:{width:900}}))assert.equal(writeGeneratedText(path,content,io),false);
 assert.equal(writeVerifiedBinary('asset',Buffer.alloc(1024,3),io),false);
 assert.equal(writes,5);assert.equal(reads,5);
 console.log(JSON.stringify({label:'A5-263/A5-277 repeated unchanged build',firstWrites:5,repeatWrites:0,repeatReads:5}));
});
