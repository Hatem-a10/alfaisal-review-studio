import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../scripts/prepare-study-assets.mjs',import.meta.url),'utf8');
function exposeBatch(){
 const begin=source.indexOf('async function orderedBatches('),end=source.indexOf('const model=',begin);
 assert.ok(begin>0&&end>begin);
 return vm.runInNewContext(source.slice(begin,end)+'\norderedBatches');
}
function exposeAdder(){
 const begin=source.indexOf('function add('),end=source.indexOf('// A5-264:',begin);
 assert.ok(begin>0&&end>begin);
 const outputs=[],registry=[],writtenDigests=new Map();
 const io=vm.createContext({registry,writtenDigests,out:'/images',path:{join:(a,b)=>a+'/'+b},writeVerifiedBinary:(p,b)=>outputs.push([p,Buffer.from(b)])});
 vm.runInContext(source.slice(begin,end)+'\nthis.add=add',io);
 return {add:io.add,outputs,registry};
}
test('A5-264 bounded image conversion finishes out-of-order work in original deterministic order',async()=>{
 const batch=exposeBatch(),rows=Array.from({length:15},(_,i)=>i),issued=[],max={value:0};let active=0;
 const start=Date.now();
 await batch(rows,3,async i=>{active++;max.value=Math.max(max.value,active);await new Promise(r=>setTimeout(r,((15-i)%3+1)*3));active--;return {id:i}},x=>issued.push(x.id));
 assert.deepEqual(issued,rows);assert.equal(max.value,3);assert.ok(Date.now()-start<800);
 console.log(JSON.stringify({label:'A5-264 bounded image-convert concurrency',assets:rows.length,maximumConcurrent:max.value,outputOrdered:true}));
});
test('A5-264 failed independent conversions may be skipped without reordering successful assets',async()=>{
 const batch=exposeBatch(),received=[];
 await batch([0,1,2,3,4,5],2,async i=>i===1||i===4?null:{id:i},item=>received.push(item.id));
 assert.deepEqual(received,[0,2,3,5]);
 assert.match(source,/await orderedBatches\(files,3,async file/);
 assert.doesNotMatch(source,/for\(const file of files\)\{try\{/);
});
test('A5-265 identical same-type SHA assets write once while retaining first URL and metadata',()=>{
 const a=exposeAdder(),data=Buffer.from('identical-data'),sha='0123456789abcdef'.repeat(4);
 const first=a.add('diagram-'+sha.slice(0,20)+'-480',data,'image/webp',sha),second=a.add('diagram-'+sha.slice(0,20)+'-960',data,'image/webp',sha);
 assert.equal(first,second);assert.equal(a.outputs.length,1);assert.equal(a.registry.length,1);
 assert.equal(a.registry[0].size,data.length);assert.equal(a.registry[0].sha,sha);
 assert.ok(first.endsWith('-480'));
 a.add('other-format',data,'image/png',sha);
 assert.equal(a.outputs.length,2,'different media types remain distinct');
 a.add('other-bytes',Buffer.from('different'), 'image/webp','2'.repeat(64));
 assert.equal(a.outputs.length,3);
});
test('A5-264/A5-265 preserve source file order and per-image width order',async()=>{
 const batch=exposeBatch(),a=exposeAdder(),entries=[];
 await batch(['a.png','b.png','a-copy.png'],2,async name=>({name,assets:[{id:'sha-a-480',buffer:Buffer.from('a'),sha:'a'.repeat(64)},{id:'sha-b-960',buffer:Buffer.from('b'),sha:'b'.repeat(64)}]}),result=>{for(const item of result.assets)entries.push([result.name,a.add(item.id,item.buffer,'image/webp',item.sha)])});
 assert.deepEqual(entries.map(([name])=>name),['a.png','a.png','b.png','b.png','a-copy.png','a-copy.png']);
 assert.equal(a.outputs.length,2,'same generated bytes across sources share the first asset');
});
