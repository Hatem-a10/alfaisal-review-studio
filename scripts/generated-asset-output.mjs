import fs from 'node:fs';
// A5-277: avoid rewriting immutable local staging assets when bytes are unchanged.
// Compare byte-for-byte, not merely by size, so stale/corrupted files are repaired.
export function writeVerifiedBinary(file,bytes,io=fs){
 if(io.existsSync(file)&&io.statSync(file).size===bytes.length&&io.readFileSync(file).equals(bytes))return false;
 io.writeFileSync(file,bytes);return true;
}
// A5-263: encode each generated JSON payload exactly once per invocation.
export function encodeGeneratedAssetOutputs(registry,diagramMap){
 const assets=JSON.stringify(registry),diagrams=JSON.stringify(diagramMap);
 return [
  ['lib/study-asset-registry.ts','// Generated by prepare-study-assets.mjs; media live in private R2.\\nexport const STUDY_ASSETS='+assets+';\\n'],
  ['public/diagram-variants.json',diagrams],
  ['public/diagram-variants.js','const DIAGRAM_VARIANTS='+diagrams+';\\n'],
  ['../heart-lab-work/asset-files.json',assets],
 ];
}
export function writeGeneratedText(file,text,io=fs){
 if(io.existsSync(file)&&io.readFileSync(file,'utf8')===text)return false;
 io.writeFileSync(file,text);return true;
}
